# 02_tables.R
# Performance summaries and the appendix tables of the manuscript.
#
# Input:  sim_res/long_n250.rds, sim_res/long_n2000.rds
# Output:
#   tables/summary_n250.csv, tables/summary_n2000.csv
#       every estimator x scenario x scale, including the [not in manuscript]
#       benchmarks and the check scenario
#   <paper_dir>/manTable_*_rows.tex (8 files)
#       table bodies \input by the appendix: median bias, RMSE and coverage of
#       the three manuscript estimators
#   <paper_dir>/simFailures.tex
#       LaTeX macros with the failure counts cited in the appendix
source("functions/shared_constants.R")

long_n250  <- readRDS("sim_res/long_n250.rds")
long_n2000 <- readRDS("sim_res/long_n2000.rds")

# --- Summaries -----------------------------------------------------------------
# Failed replications (NA estimates) are left out of every summary. rel_*:
# bias relative to each replication's truth, used where the truth varies across
# replications (the contaminated-anchor designs on the I0 metric).
summarise_long <- function(long) {
  long[, .(
    bias            = mean(bias, na.rm = TRUE),
    median_bias     = median(bias, na.rm = TRUE),
    rmse            = sqrt(mean(bias^2, na.rm = TRUE)),
    rel_median_bias = median(bias / truth, na.rm = TRUE),
    rel_rmse        = sqrt(mean((bias / truth)^2, na.rm = TRUE)),
    coverage        = mean(covered, na.rm = TRUE),
    n_fail          = sum(is.na(estimate)),
    n_total         = .N
  ), by = .(scenario, estimator, scale)]
}

summ_n250  <- summarise_long(long_n250)
summ_n2000 <- summarise_long(long_n2000)

fwrite(summ_n250,  "tables/summary_n250.csv")
fwrite(summ_n2000, "tables/summary_n2000.csv")

# --- Failure counts --------------------------------------------------------------
# A replication fails for an estimator when its I0 or SD estimate is NA: SEM-IV
# did not converge; for two-step FA-IV a CFA did not converge or returned a
# negative variance. Only the 14 reported scenarios count.
reported_scenarios <- c(names(scenario_tex_names), names(item_anchor_tex_names))

fail_by_scenario <- function(long) {
  long[scenario %in% reported_scenarios &
         estimator %in% c("SEM-IV", "Two-step FA-IV") &
         scale %in% c("I₀ anchor metric", "X SD-scaled"),
       .(failed = any(is.na(estimate))),
       by = .(estimator, scenario, iteration_id)
     ][, .(n_fail = sum(failed), n_rep = .N), by = .(estimator, scenario)]
}
fail_n250  <- fail_by_scenario(long_n250)
fail_n2000 <- fail_by_scenario(long_n2000)

tex_int <- function(x) gsub(",", "{,}", formatC(x, format = "d", big.mark = ","))
n_fail  <- function(f, est) tex_int(f[estimator == est, sum(n_fail)])

writeLines(c(
  "% Generated by 02_tables.R -- do not edit",
  sprintf("\\newcommand{\\simFailN}{%s}", tex_int(fail_n250[estimator == "SEM-IV", sum(n_rep)])),
  sprintf("\\newcommand{\\simFailSEMsmall}{%s}", n_fail(fail_n250,  "SEM-IV")),
  sprintf("\\newcommand{\\simFailSEMlarge}{%s}", n_fail(fail_n2000, "SEM-IV")),
  sprintf("\\newcommand{\\simFailTSsmall}{%s}",  n_fail(fail_n250,  "Two-step FA-IV")),
  sprintf("\\newcommand{\\simFailTSlarge}{%s}",  n_fail(fail_n2000, "Two-step FA-IV"))
), file.path(paper_dir, "simFailures.tex"))

# --- Table bodies ------------------------------------------------------------------
# One row per scenario: for each estimator, median bias & RMSE & coverage.
#   tex_names: the scenarios of the table, in row order, with their row names
#   relative:  report relative median bias and relative RMSE (contaminated anchor
#              on the I0 metric, where the truth varies across replications)
#   split:     \midrule after row 3, between the scenarios in which both
#              estimands share a verdict and those in which only theta_I0 is
#              identified
f3     <- function(x) sprintf("%.3f", round(x, 3) + 0)   # + 0 turns -0 into 0
f_prop <- function(x) sub("^0\\.", ".", sprintf("%.3f", x))   # APA: no leading zero

tex_rows <- function(summ, scale_label, estimators, tex_names,
                     relative = FALSE, split = FALSE) {
  d <- summ[scale == scale_label & estimator %in% estimators &
              scenario %in% names(tex_names)]
  if (relative) d[, `:=`(median_bias = rel_median_bias, rmse = rel_rmse)]

  d[, cells := paste(f3(median_bias), f3(rmse), f_prop(coverage), sep = " & ")]
  d[, `:=`(scenario  = factor(scenario,  levels = names(tex_names)),
           estimator = factor(estimator, levels = estimators))]
  setorder(d, scenario, estimator)

  rows <- d[, .(row = paste0(tex_names[[as.character(scenario)]], " & ",
                             paste(cells, collapse = " & "), " \\\\")),
            by = scenario]$row
  if (split) rows <- append(rows, "\\midrule", after = 3)
  c(rows, "\\bottomrule")
}

anchor_estimators <- c("SEM-IV", "Anchor-Wald", "Two-step FA-IV")
sd_estimators     <- c("SEM-IV", "Two-step FA-IV")
I0 <- "I₀ anchor metric"
SD <- "X SD-scaled"

# Gold anchor, theta_I0 and theta_SD
writeLines(tex_rows(summ_n250,  I0, anchor_estimators, scenario_tex_names, split = TRUE),
           file.path(paper_dir, "manTable_anchor_smallN_rows.tex"))
writeLines(tex_rows(summ_n2000, I0, anchor_estimators, scenario_tex_names, split = TRUE),
           file.path(paper_dir, "manTable_anchor_largeN_rows.tex"))
writeLines(tex_rows(summ_n250,  SD, sd_estimators, scenario_tex_names, split = TRUE),
           file.path(paper_dir, "manTable_sd_smallN_rows.tex"))
writeLines(tex_rows(summ_n2000, SD, sd_estimators, scenario_tex_names, split = TRUE),
           file.path(paper_dir, "manTable_sd_largeN_rows.tex"))

# Contaminated anchor (an affected item is I0), theta_I0 (relative) and theta_SD
writeLines(tex_rows(summ_n250,  I0, anchor_estimators, item_anchor_tex_names, relative = TRUE),
           file.path(paper_dir, "manTable_anchor_itemAnchor_smallN_rows.tex"))
writeLines(tex_rows(summ_n2000, I0, anchor_estimators, item_anchor_tex_names, relative = TRUE),
           file.path(paper_dir, "manTable_anchor_itemAnchor_largeN_rows.tex"))
writeLines(tex_rows(summ_n250,  SD, sd_estimators, item_anchor_tex_names),
           file.path(paper_dir, "manTable_sd_itemAnchor_smallN_rows.tex"))
writeLines(tex_rows(summ_n2000, SD, sd_estimators, item_anchor_tex_names),
           file.path(paper_dir, "manTable_sd_itemAnchor_largeN_rows.tex"))
